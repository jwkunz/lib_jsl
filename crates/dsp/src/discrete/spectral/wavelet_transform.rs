//! Wavelet transforms: the orthogonal discrete wavelet transform and the continuous wavelet
//! transform.
//!
//! # Discrete wavelet transform (DWT)
//! A pair of orthogonal quadrature-mirror filters splits a signal into a low-pass *approximation*
//! (half length) and a high-pass *detail* (half length); repeating the split on the approximation
//! gives a multi-level decomposition with logarithmic frequency resolution. The Daubechies
//! wavelets `db1` (the Haar wavelet) to `db10` are provided. `dbN` has `N` vanishing moments, so
//! polynomials of degree below `N` produce zero detail coefficients, and `2N` taps.
//!
//! The transform uses periodic extension, so it is an exactly orthogonal map: energy is preserved
//! and the inverse is the transpose. Each level needs an even length of at least the filter length.
//!
//! # Continuous wavelet transform (CWT)
//! The CWT correlates the signal with scaled copies of a mother wavelet (the complex Morlet or the
//! real Ricker "Mexican hat"), for any set of scales, giving a time-scale map. It is computed with
//! FFT correlation.

